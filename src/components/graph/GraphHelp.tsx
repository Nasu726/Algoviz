import React from 'react';
import type { GraphVariant } from './types';
import { isTraversal } from './types';

// ページごとに、そのアルゴリズムだけを説明する。
// 1ページ1アルゴリズムにしたのは、情報を詰め込みすぎないため。

const codeBlock: React.CSSProperties = {
    background: '#eceff1', padding: '8px', borderRadius: '4px', margin: '4px 0',
};

const AlgorithmSection: React.FC<{ variant: GraphVariant }> = ({ variant }) => {
    if (variant === 'bfs') return (
        <>
            <h3>1. 幅優先探索 (BFS)</h3>
            <p>
                見つけた頂点を<b>キューの末尾</b>に積み、<b>先頭から</b>取り出します。
                始点から近い頂点が先に取り出されるので、波紋のように広がります。
            </p>
            <ul>
                <li>1ステップは「辺を1本調べる」か「その頂点の隣接をすべて調べ終える」のどちらか</li>
                <li>見つかる経路は<b>辺の本数</b>で数えて最短になる</li>
                <li>重みは見ない。重みの合計で最短にしたいときは<b>ダイクストラ法</b>のページへ</li>
            </ul>
        </>
    );

    if (variant === 'dfs') return (
        <>
            <h3>1. 深さ優先探索 (DFS)</h3>
            <p>
                見つけた頂点を<b>スタックに積み、すぐそこへ潜ります</b>。
                行き止まりまで進んでから1つ戻る（バックトラック）動きが見えます。
            </p>
            <ul>
                <li>1ステップは「辺を1本調べる」か「その頂点の隣接をすべて調べ終える」のどちらか</li>
                <li>隣接を調べ終えた頂点がスタックから外れるのが、そのままバックトラック</li>
                <li>見つかる経路は最短とは限らない。最短が欲しいときは <b>BFS</b> か <b>ダイクストラ法</b>のページへ</li>
            </ul>
        </>
    );

    if (variant === 'dijkstra') return (
        <>
            <h3>1. ダイクストラ法</h3>
            <p>
                まだ確定していない頂点のうち、<b>暫定距離が最小のもの</b>を取り出して確定させます。
                取り出した頂点から伸びる辺を見て、その辺を通った方が近ければ距離と親を更新します（緩和）。
            </p>
            <ul>
                <li>取り出した瞬間にその頂点の最短距離が確定する。確定は独立した1ステップとして見せている</li>
                <li>各頂点の脇に暫定距離が出る。まだ届いていない頂点は ∞</li>
                <li>緩和で親が張り替わると、探索木の辺も引き直される</li>
                <li>見つかる経路は<b>重みの合計</b>で最短。<b>辺の本数</b>で最短にしたいときは <b>BFS</b> のページへ。この2つは一致しないことがある</li>
                <li>負の重みがあると正しい答えを出せないので、その場合は警告を出す</li>
            </ul>
        </>
    );

    return (
        <>
            <h3>1. グラフ描画</h3>
            <p>生成したグラフを表示するだけのページです。レイアウトの確認に使います。</p>
        </>
    );
};

const AutomatonHelp: React.FC<{ maxNodes: number }> = ({ maxNodes }) => (
    <>
        <h3>1. 画面の見方</h3>
        <ul>
            <li>状態は q₀, q₁, … で表示する。二重丸が受理状態、矢印が刺さっているのが初期状態</li>
            <li>辺に書かれている文字が遷移記号。同じ状態対に複数の遷移があるときは曲線に分かれる</li>
            <li>入力の欄の <b>|</b> が今どこまで読んだかを表す。左が読んだぶん、右が残り</li>
            <li>色の意味は実行状態のパネルにある凡例のとおり</li>
        </ul>

        <h3>2. 遷移規則の作り方</h3>
        <ul>
            <li><b>ランダム生成</b>：状態数とアルファベットを決めると、
                各状態から各記号への遷移を1本ずつ張る。決定性で、どの記号でも必ず遷移できる</li>
            <li><b>テキストから生成</b>：1行目に「状態数 遷移数」、続けて遷移を1行ずつ
                「元の状態 先の状態 記号」の形で書く</li>
        </ul>
        <pre style={codeBlock}>2 4{'\n'}0 1 a{'\n'}0 0 b{'\n'}1 0 a{'\n'}1 1 b</pre>
        <ul>
            <li>記号は1文字。範囲外の状態番号を含む行と、記号の無い行は読み飛ばす</li>
            <li>アルファベットは書かれた遷移から集める</li>
            <li>状態数の上限は {maxNodes}。一度に見て分かる範囲に合わせている</li>
        </ul>

        <h3>3. 実行</h3>
        <ul>
            <li>1ステップは「記号を1つ読んで遷移する」。入力を読み切った時点も1ステップとして、
                そこで受理か拒否かが決まる</li>
            <li>読んだ記号の遷移が定義されていないと、そこで止まる</li>
            <li>同じ状態から同じ記号で複数の遷移があると決定性を外れるので、警告して
                先に書かれた遷移だけを使う</li>
        </ul>

        <h3>4. 画面の操作</h3>
        <ul>
            <li><b>ドラッグ</b>：表示位置を動かす</li>
            <li><b>ホイール / 2本指のピンチ</b>：拡大・縮小</li>
        </ul>

        <h3>5. ショートカットキー</h3>
        <ul>
            <li><b>Esc</b>：ビジュアライザ一覧へ戻る</li>
            <li><b>Ctrl + H</b>：ヘルプを開く</li>
            <li><b>Ctrl + S</b>：テキストから生成</li>
            <li><b>Ctrl + Enter</b>：実行 / 一時停止</li>
            <li><b>Ctrl + ←</b> / <b>→</b>：戻る / 進む</li>
            <li><b>Ctrl + ↑</b> / <b>↓</b>：実行速度の増減</li>
        </ul>
    </>
);

export const GraphHelp: React.FC<{ variant: GraphVariant; maxNodes: number }> = ({ variant, maxNodes }) =>
    variant === 'automaton' ? <AutomatonHelp maxNodes={maxNodes} /> : (
    <>
        <AlgorithmSection variant={variant} />

        {isTraversal(variant) && (
            <p>色の意味は、実行状態のパネルにある凡例のとおりです。
                「探索木の辺」はその頂点を最初に見つけたときに通った辺、
                「調べ済みの辺」は見に行ったが既に発見済みの頂点へ向かっていた辺です。</p>
        )}

        <h3>2. グラフの作り方</h3>
        <ul>
            <li><b>ランダム生成</b>：頂点数と辺の数を指定して作る</li>
            <li><b>連結なグラフにする</b>：全域木を先に張るので、途中で行き止まりにならない。
                有向のときは頂点 0 を根にするので、始点を 0 にすれば必ず全頂点へ届く。
                辺の数が V-1 に満たない指定は V-1 まで増やす</li>
            <li><b>完全グラフ生成</b>：すべての頂点対を辺で結ぶ</li>
        </ul>

        <h3>3. グラフの入力</h3>
        <p>1行目に「頂点数 辺数」、続けて辺を1行ずつ「始点 終点 重み」の形で書きます。重みは省略できます。</p>
        <pre style={codeBlock}>4 4{'\n'}0 1 5{'\n'}1 2 3{'\n'}2 3 7{'\n'}0 3</pre>
        <p>「頂点の重みを入力する」にチェックを入れると、「頂点数 辺数」の次の行で頂点の重みを並べられます。</p>
        <pre style={codeBlock}>3 2{'\n'}10 20 30{'\n'}0 1 5{'\n'}1 2 5</pre>
        <ul>
            <li>辺の重みを書かないと 1 として扱う。重み無しグラフのダイクストラ法は BFS と同じ結果になる</li>
            <li>範囲外の頂点番号を含む行は読み飛ばす</li>
            <li>頂点数の上限は {maxNodes}。一度に見て分かる範囲に合わせている</li>
            <li>「有向グラフ」のチェックは生成時に反映される。探索が辺の向きを守るかどうかもこれで決まる</li>
        </ul>

        <h3>4. 画面の操作</h3>
        <ul>
            <li><b>ドラッグ</b>：表示位置を動かす</li>
            <li><b>ホイール / 2本指のピンチ</b>：拡大・縮小。縮小しすぎると文字は表示されなくなる</li>
            <li>グラフを作り直すと、自動で全体が画面に収まる位置に戻る</li>
        </ul>

        <h3>5. ショートカットキー</h3>
        <ul>
            <li><b>Esc</b>：ビジュアライザ一覧へ戻る</li>
            <li><b>Ctrl + H</b>：ヘルプを開く</li>
            <li><b>Ctrl + S</b>：テキストからグラフを生成</li>
            {isTraversal(variant) && <>
                <li><b>Ctrl + Enter</b>：実行 / 一時停止</li>
                <li><b>Ctrl + ←</b> / <b>→</b>：戻る / 進む</li>
                <li><b>Ctrl + ↑</b> / <b>↓</b>：実行速度の増減</li>
            </>}
        </ul>
    </>
);
